-- 185: East Asian era dates beside the Gregorian ones (owner 2026-11-02: "dates of the japanese calendar with showa 12
-- and so on … and if there is something similar for korea and/or china"). A work made in Japan in 1831 also reads
-- "Tenpō 2 (天保2年) · 辛卯"; a Korean one of 1749 "Yeongjo 25 (英祖 25年)"; a Chinese one of 1740 "Qianlong 5".
--
-- calendar_eras: one row per era (Japan's nengō, China's reign eras) or reign (Joseon's kings, whose years Korean
-- sources count: "영조 25년"). `period` is a generated daterange [starts, ends), and an exclusion constraint (GiST, with
-- btree_gist for the text columns) makes sure two eras of the same line never overlap — the lines are what may run side
-- by side: Japan's Southern Court (1336–1392) beside the Northern, Ming beside Qing in 1644. Year 1 of an era is
-- `year_one`: in Japan the year of the change (1868 = Keiō 4 and Meiji 1); in Joseon the year after the accession
-- (踰年稱元), except the founder and the kings who replaced another by force (Taejo, Sejo, Jungjong, Injo:
-- 卽位年稱元) — their rows are year-aligned, the Japanese ones start on the day of the change.
-- Era years are lunar years until the solar calendar (Japan 1873, Korea 1896, China 1912): Tenpō began on the 10th day
-- of the 12th month of 1830 — 23 January 1831 —, so 1831 is Tenpō 2. lunar_new_years holds the first day of each
-- lunar year 640–1912, computed (the second new moon after the winter solstice by local day, Japan time; Meeus,
-- Astronomical Algorithms ch. 27, 49 — checked against 13 known dates 1831–2033). The historical calendars (Japan's
-- Senmyō calendar until 1684) could differ by a day or two: a date that close to a new year is marked `approx`.
-- A whole year (a date given as "1831") is read as the lunar year: from its new year on. An era Wikidata dates only
-- to a year or a month has that year as its year 1.
-- Data: Wikidata (Japanese era names Q24706 with their start dates, Julian ones converted; Chinese era names Q845538;
-- holders of "king of Joseon" Q22304810 with their accession), 2026-11-02. Not included: the unofficial Hakuhō and
-- Suzaku, China before the Ming (Wikidata's lists have gaps), Korea before Joseon.

CREATE TABLE calendar_eras (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  calendar text NOT NULL CHECK (calendar IN ('jp', 'kr', 'cn')),
  line text NOT NULL DEFAULT '',              -- '' = the main line; 'Southern Court', 'Ming', 'Qing'
  name text NOT NULL,                          -- romanized: Tenpō, Qianlong, Yeongjo
  native text NOT NULL,                        -- 天保, 乾隆, 英祖
  hangul text,                                 -- Korea: 영조
  starts date NOT NULL,
  ends date,                                   -- exclusive; null = still running (Reiwa)
  year_one int NOT NULL,                       -- the Gregorian year that is its year 1
  kind text NOT NULL CHECK (kind IN ('era', 'reign')),
  wikidata_id text CHECK (wikidata_id ~ '^Q[0-9]+$'),
  note text,
  period daterange GENERATED ALWAYS AS (daterange(starts, ends)) STORED,
  CHECK (ends IS NULL OR ends > starts),
  CONSTRAINT calendar_eras_no_overlap EXCLUDE USING gist (calendar WITH =, line WITH =, period WITH &&)
);
COMMENT ON TABLE calendar_eras IS 'East Asian eras and reigns for era dates beside Gregorian ones (185)';
GRANT SELECT ON calendar_eras TO arthistory_api, arthistory_admin;


