-- the day a calendar became solar (Japan: Meiji 5/12/3 = 1 January 1873; Korea: 1 January 1896; China: 1912)
CREATE FUNCTION solar_since(cal text) RETURNS date
LANGUAGE sql IMMUTABLE AS $$ SELECT CASE cal WHEN 'jp' THEN date '1873-01-01' WHEN 'kr' THEN date '1896-01-01' ELSE date '1912-01-01' END $$;

-- the (lunar, before solar_since) year a day belongs to: 20 January 1831 is still 1830
CREATE FUNCTION lunar_year(cal text, d date) RETURNS int
LANGUAGE sql STABLE AS $$
  SELECT extract(year FROM d)::int - CASE WHEN d < solar_since(cal)
    AND d < (SELECT n.day FROM lunar_new_years n WHERE n.year = extract(year FROM d)::int) THEN 1 ELSE 0 END
$$;

-- one era year as text: "Tenpō 2" / "天保2年" (year 1: 元年); Korea's hangul "영조 25년" (원년)
CREATE FUNCTION era_year_text(e calendar_eras, y int, form text) RETURNS text
LANGUAGE sql IMMUTABLE AS $$
  SELECT CASE form
    WHEN 'name' THEN e.name || ' ' || (y - e.year_one + 1)
    WHEN 'hangul' THEN e.hangul || ' ' || CASE WHEN y = e.year_one THEN '원년' ELSE (y - e.year_one + 1) || '년' END
    ELSE e.native || CASE WHEN e.calendar = 'kr' THEN ' ' ELSE '' END || CASE WHEN y = e.year_one THEN '元年' ELSE (y - e.year_one + 1) || '年' END
  END
$$;

-- the sexagenary year (干支), shared by all three: 1984 = 甲子
CREATE FUNCTION sexagenary_year(y int) RETURNS text
LANGUAGE sql IMMUTABLE AS $$
  SELECT substr('甲乙丙丁戊己庚辛壬癸', ((y - 4) % 10 + 10) % 10 + 1, 1) || substr('子丑寅卯辰巳午未申酉戌亥', ((y - 4) % 12 + 12) % 12 + 1, 1)
$$;

-- A date range in a calendar → {calendar, parts: [{line, label, native, hangul}], sexagenary, approx} or null.
-- The start is the era in effect on the range's first day, the end the one on its last; one era: "Tenpō 1–3"; a single
-- year with a change in it: "Keiō 4 / Meiji 1"; a range of more than 60 years (a century) gets none.
CREATE FUNCTION era_label(cal text, d daterange) RETURNS jsonb
LANGUAGE sql STABLE AS $$
  WITH r AS (
    SELECT lower(d) AS f0, upper(d) - 1 AS t
    WHERE cal IS NOT NULL AND NOT isempty(d) AND lower(d) IS NOT NULL AND upper(d) IS NOT NULL
  ),
  b AS (
    -- a range from a 1 January before the solar calendar starts with that year's lunar new year
    SELECT CASE WHEN extract(doy FROM r.f0) = 1 AND r.f0 < solar_since(cal)
                THEN coalesce((SELECT n.day FROM lunar_new_years n WHERE n.year = extract(year FROM r.f0)::int), r.f0) ELSE r.f0 END AS f,
           r.t, r.f0
    FROM r
  ),
  y AS (SELECT b.*, daterange(b.f, b.t, '[]') AS span FROM b),
  -- per line the first and the last era in effect within the range; each end's year kept within its era (the whole
  -- year 1910 in Korea is Yunghui 4: the empire ended in August)
  ends AS (
    SELECT l.line, s0.s, e0.e,
           greatest(lunar_year(cal, greatest(y.f, (s0.s).starts)), (s0.s).year_one) AS sy,
           lunar_year(cal, least(y.t, coalesce((e0.e).ends - 1, y.t))) AS ey
    FROM y
    CROSS JOIN LATERAL (SELECT DISTINCT x.line FROM calendar_eras x WHERE x.calendar = cal AND x.period && y.span) l
    CROSS JOIN LATERAL (SELECT x AS s FROM calendar_eras x WHERE x.calendar = cal AND x.line = l.line AND x.period && y.span ORDER BY x.starts LIMIT 1) s0
    CROSS JOIN LATERAL (SELECT x AS e FROM calendar_eras x WHERE x.calendar = cal AND x.line = l.line AND x.period && y.span ORDER BY x.starts DESC LIMIT 1) e0
    WHERE lunar_year(cal, y.t) - lunar_year(cal, y.f) <= 60
  ),
  per_line AS (
    SELECT n.line,
           CASE WHEN (n.s).id = (n.e).id AND n.sy = n.ey THEN era_year_text(n.s, n.sy, 'name')
                WHEN (n.s).id = (n.e).id THEN era_year_text(n.s, n.sy, 'name') || '–' || (n.ey - (n.e).year_one + 1)
                ELSE era_year_text(n.s, n.sy, 'name') || CASE WHEN n.sy = n.ey THEN ' / ' ELSE ' – ' END || era_year_text(n.e, n.ey, 'name') END AS label,
           CASE WHEN (n.s).id = (n.e).id AND n.sy = n.ey THEN era_year_text(n.s, n.sy, 'native')
                WHEN (n.s).id = (n.e).id THEN era_year_text(n.s, n.sy, 'native') || '–' || (n.ey - (n.e).year_one + 1) || '年'
                ELSE era_year_text(n.s, n.sy, 'native') || CASE WHEN n.sy = n.ey THEN ' / ' ELSE '–' END || era_year_text(n.e, n.ey, 'native') END AS native,
           CASE WHEN (n.s).hangul IS NULL OR (n.e).hangul IS NULL THEN NULL
                WHEN (n.s).id = (n.e).id AND n.sy = n.ey THEN era_year_text(n.s, n.sy, 'hangul')
                WHEN (n.s).id = (n.e).id THEN era_year_text(n.s, n.sy, 'hangul') || '–' || (n.ey - (n.e).year_one + 1) || '년'
                ELSE era_year_text(n.s, n.sy, 'hangul') || CASE WHEN n.sy = n.ey THEN ' / ' ELSE ' – ' END || era_year_text(n.e, n.ey, 'hangul') END AS hangul,
           n.sy, n.ey
    FROM ends n
    WHERE n.sy <= n.ey
  )
  SELECT jsonb_build_object(
           'calendar', cal,
           'parts', jsonb_agg(jsonb_strip_nulls(jsonb_build_object('line', nullif(p.line, ''), 'label', p.label, 'native', p.native, 'hangul', p.hangul))
                              ORDER BY p.line <> '', p.line),
           'sexagenary', CASE WHEN min(p.sy) = max(p.ey) THEN sexagenary_year(min(p.sy)) END,
           -- a given day within two days of a computed new year, before the solar calendar
           'approx', bool_or(y.t < solar_since(cal) AND y.t - y.f0 < 360 AND EXISTS (SELECT 1 FROM lunar_new_years n
                       WHERE abs(n.day - y.f0) <= 2 OR abs(n.day - y.t) <= 2)))
  FROM per_line p CROSS JOIN y
  HAVING count(*) > 0
$$;

-- Which calendar an entry's dates are also given in: its country (where a work was made, where a person was born,
-- where an event took place); for a work else its artist's, else the country its periods were active in (Mason's and
-- Portal's works are linked to Heian, Edo, Joseon … rather than to a place); for a person else their periods'.
CREATE FUNCTION entry_calendar(etype entity_type, eid bigint) RETURNS text
LANGUAGE sql STABLE AS $$
  WITH codes AS (
    SELECT 1 AS rank, entity_country(etype, eid)->>'code' AS code
    UNION ALL
    SELECT 2, entity_country('artist', w.creator_id)->>'code' FROM artworks w WHERE etype = 'artwork' AND w.id = eid AND w.creator_id IS NOT NULL
    UNION ALL
    SELECT 3, (SELECT place_country(r.object_id)->>'code'
                 FROM relationships r
                WHERE r.subject_type = 'movement' AND r.relationship_type = 'active_in' AND r.object_type = 'place'
                  AND r.subject_id IN (SELECT movement_id FROM movement_works WHERE etype = 'artwork' AND artwork_id = eid
                                       UNION SELECT movement_id FROM movement_artists WHERE etype IN ('artist', 'person') AND artist_id = eid)
                  AND place_country(r.object_id)->>'code' IN ('JP', 'KR', 'CN')
                ORDER BY r.id LIMIT 1)
  )
  SELECT CASE code WHEN 'JP' THEN 'jp' WHEN 'KR' THEN 'kr' WHEN 'CN' THEN 'cn' END
  FROM codes WHERE code IS NOT NULL ORDER BY rank LIMIT 1
$$;

-- An entry's dates in its calendar (API detail `eras`): a work's creation, a person's birth and death, an event's span.
CREATE FUNCTION entry_eras(etype entity_type, eid bigint) RETURNS jsonb
LANGUAGE plpgsql STABLE AS $$
DECLARE
  cal text := entry_calendar(etype, eid);
  out jsonb;
BEGIN
  IF cal IS NULL THEN RETURN NULL; END IF;
  out := CASE etype
    WHEN 'artwork' THEN (SELECT jsonb_build_object('created', era_label(cal, created)) FROM artworks WHERE id = eid)
    WHEN 'artist' THEN (SELECT jsonb_build_object('birth', era_label(cal, birth), 'death', era_label(cal, death)) FROM artists WHERE id = eid)
    WHEN 'person' THEN (SELECT jsonb_build_object('birth', era_label(cal, birth), 'death', era_label(cal, death)) FROM people WHERE id = eid)
    WHEN 'event' THEN (SELECT jsonb_build_object('period', era_label(cal, period)) FROM events WHERE id = eid)
  END;
  out := jsonb_strip_nulls(out);
  RETURN CASE WHEN out IS NULL OR out = '{}' THEN NULL ELSE out END;
END $$;
