-- Source: the DDBC/DILA Time Authority database (Dharma Drum Institute of Liberal Arts, Taipei; snapshot 2012-02,
-- authority.dila.edu.tw), CC BY-SA 3.0 — every era and reign with the first and last day of each of its months.
-- China: the line of succession as Chinese chronology counts it — Tang (with Wu Zetian's Zhou), the Five Dynasties,
-- Song (Northern and Southern, to 1279), Yuan (with Kublai's eras from 1260, to the Ming's beginning); the courts beside
-- them in the north (Liao, Jin, Western Xia) are left out. An era DILA splits at a change of emperor is one row;
-- 761–762 stays without an era (Suzong's years without a name). Romanized in pinyin (four characters as two words:
-- Taiping Xingguo; 大和 of 827–835 = Taihe).
-- Korea: the kings' reign years, as Korean sources count them (충렬왕 25년) — Goryeo (918–1392), Silla, Goguryeo and
-- Baekje as lines of their own (the Three Kingdoms side by side; Goryeo's end overlaps Joseon's year-aligned start);
-- a second reign (忠肅王, 忠惠王: 後元) is a row of its own. Year 1 as DILA counts it, never before the reign began.
-- Revised Romanization with the sound changes (충렬 → Chungnyeol).
-- lunar_new_years before 640: the first day of month 1 of the Chinese main dynasties (Western Han to Tang) from
-- DILA — 58 BC to 639 (13, 16 and 19 CE missing: Wang Mang's Xin began the year in another month). lunar_year()
-- now counts astronomically (1 BC = 0), so a reign across the beginning of our era (Hyeokgeose, 57 BC – 4 CE) counts
-- on without a year 0; from year 1 on nothing changes.

CREATE OR REPLACE FUNCTION public.lunar_year(cal text, d date) RETURNS integer LANGUAGE sql STABLE AS $function$
  SELECT (CASE WHEN extract(year FROM d) < 0 THEN extract(year FROM d)::int + 1 ELSE extract(year FROM d)::int END)
       - CASE WHEN d < solar_since(cal) AND d < (SELECT n.day FROM lunar_new_years n WHERE n.year = extract(year FROM d)::int) THEN 1 ELSE 0 END
$function$;

